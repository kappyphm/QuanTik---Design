import { test, expect } from "@playwright/test";

test("Phân tích có diễn giải, biểu đồ và 3D xoay được, dừng theo reduced motion", async ({ page }) => {
  const errors: string[] = [], calls: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (/\/api\/|\/quant\/jobs/.test(r.url())) calls.push(r.url()); });
  await page.goto("/analysis?symbol=FPT");
  await page.getByRole("button", { name: "Xem kết quả mẫu", exact: true }).click();
  await expect(page.getByRole("region", { name: "Hành động" })).toContainText("Nếu chưa mua");
  await expect(page.getByRole("region", { name: "Hành động" })).toContainText("Nếu đang cầm hàng");
  await expect(page.getByRole("img", { name: /Giá và trạng thái HMM FPT/ })).toBeVisible();
  const hmm = page.locator(".quant-report-section").filter({ has: page.locator("summary strong", { hasText: "HMM & Hurst" }) });
  await hmm.getByRole("button", { name: "Hiểu mô hình", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "HMM & Hurst", exact: true })).toContainText("Đây là xác suất trạng thái ẩn của mô hình, không phải xác suất giao dịch thắng.");
  await page.keyboard.press("Escape");
  const garch = page.getByRole("group", { name: "Góc nhìn GARCH", exact: true });
  await garch.getByRole("button", { name: "Mô hình 3D", exact: true }).click();
  const canvas = page.getByRole("img", { name: /GARCH 3D FPT/ });
  await expect(canvas).toBeVisible();
  await expect(canvas).toHaveJSProperty("width", await canvas.evaluate(el => Math.round(el.getBoundingClientRect().width * Math.min(devicePixelRatio, 2))));
  const before = await canvas.evaluate(el => (el as HTMLCanvasElement).toDataURL());
  await canvas.focus();
  await page.keyboard.press("ArrowRight");
  expect(await canvas.evaluate(el => (el as HTMLCanvasElement).toDataURL())).not.toBe(before);
  await page.getByRole("button", { name: "Phát chuyển động", exact: true }).click();
  await expect(page.getByRole("button", { name: "Tạm dừng", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Tạm dừng", exact: true }).click();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await expect(page.getByRole("button", { name: "Phát chuyển động", exact: true })).toBeDisabled();
  await page.screenshot({ path: `test-results/ui/${test.info().project.name}/analysis.png`, fullPage: true });
  const monte = page.getByRole("group", { name: "Góc nhìn Monte Carlo", exact: true });
  await monte.getByRole("button", { name: "Phân phối", exact: true }).click();
  await expect(page.getByRole("img", { name: /Phân phối lợi suất cuối kỳ FPT/ })).toBeVisible();
  await monte.getByRole("button", { name: "Mô hình 3D", exact: true }).click();
  await expect(page.getByRole("img", { name: /Monte Carlo 3D FPT/ })).toBeVisible();
  await page.getByRole("button", { name: "Chuyển chế độ sáng", exact: true }).click();
  const sizes = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
  expect(sizes.scroll).toBeLessThanOrEqual(sizes.width + 1);
  expect(errors).toEqual([]);
  expect(calls).toEqual([]);
});

test("Sidebar chỉ nạp biểu đồ khi mở diễn giải, mã quét cũng có báo cáo", async ({ page }) => {
  await page.goto("/dashboard");
  await page.getByPlaceholder("Tìm mã hoặc tên").fill("FPT");
  await page.getByRole("button", { name: "FPT", exact: true }).click();
  const chart = page.getByRole("dialog", { name: "Biểu đồ FPT", exact: true });
  await chart.getByRole("button", { name: "Xem kết quả mẫu", exact: true }).click();
  await expect(chart.locator(".quant-report-section[open]")).toHaveCount(0);
  await expect(chart.locator(".quant-report canvas, .quant-report .quant-plot-svg")).toHaveCount(0);
  await chart.locator(".quant-report-section > summary").filter({ hasText: "HMM & Hurst" }).click();
  await expect(chart.getByRole("img", { name: /Giá và trạng thái HMM FPT/ })).toBeVisible();
  await chart.getByRole("link", { name: "Đọc toàn bộ phân tích", exact: false }).click();
  await expect(page).toHaveURL(/analysis\?symbol=FPT/);
  await page.goto("/screener");
  await page.getByRole("button", { name: "Quét toàn sàn", exact: true }).click();
  const first = page.locator(".scan-item").first();
  await first.getByText("Vì sao nổi bật?", { exact: true }).click();
  await first.locator(".quant-report-section > summary").filter({ hasText: "Monte Carlo" }).click();
  await expect(first.getByRole("img", { name: /Dải giá Monte Carlo DRI/ })).toBeVisible();
});

test("Hồ sơ nhân tố có số liệu gốc, diễn giải và cột 3D điều khiển được",async({page})=>{
  await page.goto('/analysis?symbol=FPT');
  await page.getByRole('button',{name:'Xem kết quả mẫu',exact:true}).click();
  await expect(page.getByRole('img',{name:/Hồ sơ nhân tố FPT/})).toBeVisible();
  const profile=page.locator('.factor-profile');
  await profile.locator('.factor-row').filter({hasText:'Dòng tiền'}).click();
  await expect(profile.locator('.factor-interpretation')).toContainText('áp lực mua');
  await profile.getByRole('button',{name:'Cột 3D',exact:true}).click();
  await expect(page.getByRole('img',{name:'Cột nhân tố 3D FPT',exact:true})).toBeVisible();
  const world=profile.locator('.factor-three-world');
  const before=await world.getAttribute('style');
  await profile.getByLabel('Xoay góc nhìn').fill('30');
  expect(await world.getAttribute('style')).not.toBe(before);
  await expect(page.getByRole('img',{name:'Drawdown từ chuỗi giá mẫu FPT',exact:true})).toBeVisible();
});
